#!/usr/bin/env python3
"""Port the MediaTek telephony property labels and rules from the owner's own stock firmware policy.

Why: stock labels MediaTek telephony/IMS system properties with its own types (system_mtk_*_prop, defined in the
stock system_ext policy) and lets the phone domains use them. Our GSI image has none of that, so e.g. the IMS app
cannot read persist.vendor.mtk_rcs_single_reg_support and the capability helper cannot set vendor.ril.capctrl_loaded.

Input : stock system_ext_sepolicy.cil and system_ext_property_contexts (extracted from the stock system_a.img)
Output: pg_mtk_telephony.te, property_contexts   (into the given output directory)
Only property types (system_mtk_*_prop) and only rules whose subject is one of DOMAINS are ported.
"""
import re, sys, os
cil, spc, outdir = sys.argv[1:4]
DOMAINS = ("radio", "system_server", "platform_app", "system_app")
rules = []
for l in open(cil):
    m = re.match(r"\(allow (\S+) (\S+) \((\S+) \(([^)]*)\)\)\)", l.strip())
    if m and m.group(1) in DOMAINS and m.group(2).startswith("system_mtk_") and m.group(2).endswith("_prop"):
        rules.append((m.group(1), m.group(2), m.group(3), m.group(4).split()))
types = sorted({r[1] for r in rules})
lines = [l.rstrip("\n") for l in open(spc)]
ctx = [l for l in lines if l.strip() and not l.lstrip().startswith("#") and re.search(r":(%s):s0" % "|".join(types), l)]
te = ["# Generated by build/tools/port_mtk_policy.py from the stock Qin system_ext policy. Do not edit by hand.",
      "# MediaTek telephony property types and the access stock gives the phone domains.", ""]
for t in types: te.append("type %s, property_type;" % t)
te.append("")
seen = set()
for dom, t, cls, perms in rules:
    if cls == "property_service" and "set" in perms and (dom, t, "set") not in seen:
        te.append("set_prop(%s, %s)" % (dom, t)); seen.add((dom, t, "set"))
    elif cls == "file" and "read" in perms and (dom, t, "get") not in seen:
        te.append("get_prop(%s, %s)" % (dom, t)); seen.add((dom, t, "get"))
te += ["", "# SMS-ready flag set by the vendor RIL daemon (labelled vendor_default_prop here; stock allows it through its own policy).",
       "set_prop(rild, vendor_default_prop)", ""]
os.makedirs(outdir, exist_ok=True)
open(os.path.join(outdir, "pg_mtk_telephony.te"), "w").write("\n".join(te))
open(os.path.join(outdir, "property_contexts"), "w").write("\n".join(ctx) + "\n")
print("types: %d, rules: %d, property context lines: %d" % (len(types), len(seen), len(ctx)))
